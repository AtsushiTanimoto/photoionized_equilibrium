def value(model, quantity, code):
    """そのモデル・量・コードの公表値 (なければ None)"""
    reference = MODELS[model]
    if code not in reference["columns"] or quantity not in reference["rows"]:
        return None
    return reference["rows"][quantity][reference["columns"].index(code)]


def median(model, quantity):
    """MOCASSIN (BE3D, BE1D) 以外のコードの値の中央値 (なければ None)"""
    reference = MODELS[model]
    if quantity not in reference["rows"]:
        return None
    values = [v for code, v in zip(reference["columns"], reference["rows"][quantity]) if v is not None and not code.startswith("BE")]
    return float(numpy.median(values)) if values else None
